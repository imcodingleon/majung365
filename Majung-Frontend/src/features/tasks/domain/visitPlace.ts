// 방문 예약을 받는 곳 (2026-08-31).
//
// **전에는 `contact.org`를 방문지로 썼는데 그것은 전화 문의처다.** `route-contacts.md`의
// 표 제목이 "지원 항목별 담당 기관 연락처"이고 용도가 "AI 답변 끝에 서버가 붙이는
// 연락처"다. 갈 곳을 적은 표가 아니다.
//
// 그래서 화면에 이런 것들이 떴다.
//   신분증        → "정부민원안내콜센터에 방문 예약하기"   (콜센터에 방문 예약)
//   생계급여      → "보건복지상담센터에 방문 예약하기"
//   주민등록 주소  → "정부민원안내콜센터에 방문 예약하기"
//   심리상담      → "정신건강 위기상담전화에 방문 예약하기" (전화번호에 방문 예약)
//
// 지원 항목마다 실제로 찾아가는 곳을 여기에 적는다. 전화번호 표와 섞이지 않게 파일을 나눴다.
import type { RouteId } from "@/shared/types/route";

export type VisitPlace = {
  /** 버튼에 나오는 기관 이름. */
  label: string;
  /**
   * 아직 그 기관과 예약 연동이 되지 않은 곳.
   *
   * **협의 중인 기관에는 요청을 보내지 않는다.** 보내도 받는 쪽이 없어서 사용자는
   * 답을 기다리다 만다. 버튼을 지우는 대신 흐리게 두고 왜 못 누르는지 알린다 —
   * 없애 버리면 그 기관에는 갈 수 없는 것으로 읽힌다.
   */
  pending?: boolean;
};

/**
 * 지원 항목별 방문지.
 *
 * 여기 없는 항목은 방문 예약 버튼이 나오지 않는다. 서버가 `visitLabel`을 주지 않는
 * 항목(R10 통장·R14 개인회생)이 그렇고, 그것은 갈 곳이 은행·법원이라 담당자가
 * 미리 알 수 있는 일이 아니기 때문이다.
 */
const PLACES: Partial<Record<RouteId, VisitPlace>> = {
  R1: { label: "한국법무보호복지공단" }, // 숙식제공
  R2: { label: "한국법무보호복지공단" }, // 공단 긴급지원
  R3: { label: "한국법무보호복지공단" }, // 기초건강지원
  R4: { label: "한국법무보호복지공단" }, // 주거지원
  R6: { label: "한국법무보호복지공단" }, // 취업·허그일자리
  R7: { label: "한국법무보호복지공단" }, // 창업지원

  // 아래는 아직 그 기관과 협의 중이다.
  R8: { label: "인근 정신건강복지센터", pending: true }, // 심리상담
  R9: { label: "인근 행정복지센터", pending: true }, // 신분증
  R11: { label: "인근 행정복지센터", pending: true }, // 주민등록 주소
  R12: { label: "인근 행정복지센터", pending: true }, // 생계급여
  R15: { label: "국민건강보험공단", pending: true }, // 의료급여·건강보험
};

export function visitPlaceOf(routeId: RouteId): VisitPlace | undefined {
  return PLACES[routeId];
}

/** 협의 중인 기관을 눌렀을 때 알리는 말. 버튼마다 적지 않고 한 자리에 둔다. */
export const VISIT_PENDING_NOTE = "해당 기관과는 협의 중입니다.";
