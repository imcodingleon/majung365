// 팝업 닫기를 한 틱 미룬다.
//
// **웹에서 팝업을 그 자리에서 닫으면 같은 클릭이 뒤 화면으로 샌다.** Pressable은
// pointerup에서 onPress를 부르는데, 거기서 팝업을 없애면 뒤이어 오는 click 이벤트가
// 사라진 팝업 자리에 새로 드러난 요소로 간다.
//
// 실제로 **생일을 고르는 클릭이 뒤 화면의 죄목까지 눌렀다.** 죄목은 민감정보이고
// 사용자가 고른 적 없는 값이 들어가므로 그냥 둘 수 없다. 한 틱을 미루면 click 이벤트가
// 아직 남아 있는 팝업 위에서 소진된다.
//
// 앱(iOS·안드로이드)에서는 이 문제가 없지만, 미루는 것 자체가 해가 없어 갈래를 나누지
// 않는다. 갈라 두면 웹에서만 나는 문제를 앱에서 재현하려다 시간을 버린다.

/** 넘긴 함수를 다음 틱에 부른다. 팝업을 닫는 자리에 쓴다. */
export function deferClose(close: () => void): () => void {
  return () => {
    setTimeout(close, 0);
  };
}
