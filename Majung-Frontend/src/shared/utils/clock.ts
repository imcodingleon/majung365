// 시각을 사람이 읽는 말로 바꾼다.
//
// **여기 있는 이유는 담당자 화면과 사용자 화면이 같은 말을 써야 하기 때문이다.**
// 사용자가 "오전 10시"를 골랐는데 담당자 화면에 "오전"까지만 뜨면, 담당자는 몇 시에
// 맞춰야 할지 모른 채 사용자에게 다시 물어야 한다. 두 화면이 각자 이 계산을 들면
// 한쪽만 고치고 짝을 빠뜨리는 일이 또 생긴다.

/** 오전 9시 → "오전 9시". 정오는 "낮 12시"로 부른다 — "오후 0시"는 읽히지 않는다. */
export function hourLabel(hour: number): string {
  return hour < 12 ? `오전 ${hour}시` : hour === 12 ? "낮 12시" : `오후 ${hour - 12}시`;
}
