-- 확정된 방문 시각 — 기획서 §7.1
--
-- **만나기로 한 시각을 담을 자리가 없었다.** 있는 것은 이랬다.
--
--   preferred_at_1   사용자가 고른 1지망
--   preferred_at_2   2지망
--   proposed_at      담당자가 다른 시간을 제안했을 때 그 시간
--   confirmed_at     확정 처리를 누른 시각      ← 만나는 시각이 아니다
--
-- 화면이 confirmed_at을 만나는 시각으로 쓰다가 실제로 이런 문구가 나왔다.
--
--   "8월 24일 월요일 오전으로 정해졌어요"
--
-- 확정을 누른 시각이 15:10Z, 곧 한국 시각 자정 10분이라 "오전"이 된 것이다.
-- **출소자에게 새벽에 만나자는 안내가 나갈 뻔했다.**
--
-- 담당자가 확정할 때 시각을 함께 보낸다. 안 보내면 1지망으로 채운다 —
-- 대부분 1지망으로 확정되고, 매번 입력하게 하면 빼먹었을 때 확정 자체가
-- 막힌다. 장소를 필수로 둔 것과 다른 판단인데, **장소는 서버가 알 수 없는
-- 정보이고 시각은 이미 1지망이 있기 때문이다.**

alter table visit_request
  add column if not exists confirmed_for timestamptz;
