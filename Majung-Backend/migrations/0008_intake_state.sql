-- 세션이 끊겨도 할 일을 이어서 본다 — 기획서 §5.2·§9.1
--
-- **왜 필요한가.** 가입을 마치고 할 일을 하던 중 앱을 닫거나 새로고침하면 가입
-- 화면부터 다시 시작한다. 진단 답변도 계산된 할 일도 기기 메모리에만 있었기
-- 때문이다. 27문항을 다시 답하게 하는 것은 이 사용자층에게 특히 무거운 요구다.
--
-- **그런데 답변 자체는 여전히 저장하지 않는다.** 0006이 그 이유를 적어 두었다 —
-- "오늘 밤 잘 곳이 없다 · 통장이 압류됐다 · 정신과 상담이 필요하다"가 한 줄에
-- 모이면 출소 사실보다 구체적인 취약성 목록이 되고, 유출 피해가 이름·생일보다
-- 크다. 그 판단은 지금도 유효하다.
--
-- **대신 판정 결과만 남긴다.** 할 일을 계산하는 데 필요한 것은 답변 원문이 아니라
-- `IntakeVerdict` 여섯 필드다(지원 항목·분야·선행조건 여부·상태·지정 제도·지정
-- 근거). 카드 본문은 지식 베이스에서 다시 만들어지므로 여기 담을 필요가 없고,
-- 지식 베이스가 갱신되면 복원된 화면도 최신 안내를 받는다.
--
-- 답변 원문과 비교하면 남는 것이 이만큼 줄어든다.
--   답변: "빚이 3,200만 원이고 통장이 압류됐다 · 정신과 약을 먹는다"
--   판정: R12 / S2 / blocks_others=false / state=BLOCKED / lead=debt_seizure
--
-- **완료 여부는 평문이다** (§9.2가 정한 구분 그대로다). 어떤 항목을 마쳤는지는
-- 판정 목록을 이미 아는 사람에게 새로운 사실을 더해 주지 않는다.

create table if not exists intake_state (
  -- 사용자당 한 행. 가입 때 만들고 완료할 때마다 갱신한다.
  user_id uuid primary key references app_user (id) on delete cascade,

  -- IntakeVerdict 목록을 JSON으로 담아 암호화한다.
  --
  -- **평문으로 두지 않는 이유**는 어떤 지원 항목이 배정됐는지가 그 자체로 상황을
  -- 말하기 때문이다. R1(숙식제공)이 있으면 잘 곳이 없다는 뜻이다. 답변 원문보다
  -- 덜 구체적일 뿐 무해한 값이 아니다.
  verdicts_enc text not null,

  -- 마친 지원 항목의 번호들. 예: {"R9","R4"}
  completed text[] not null default '{}',

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- **계정이 지워지면 함께 지워진다** (§9.4). on delete cascade가 그 일을 한다.
-- 지운 뒤에 남는 것이 없어야 §3.5의 고지가 거짓말이 되지 않는다.

comment on table intake_state is
  '초기 진단 판정 결과와 완료 상태. 답변 원문은 담지 않는다 (§9.1 데이터 최소화).';
