-- 마지막으로 알아낸 위치 (2026-08-26 결정 F-1).
--
-- **예선부터 이어온 "좌표를 우리 서버로 보내지 않는다"를 뒤집은 것이다.** 시군구까지만
-- 아는 서버는 그 동네 기관들의 한가운데로 거리를 쟀는데, 시군구 안에서 그 한가운데가
-- 엉뚱한 곳을 가리켰다 — 군포시는 기관이 산본신도시에 몰려 있어, 군포역에 사는
-- 사람에게 산본 주민센터가 먼저 나왔다.
--
-- **이력이 아니라 마지막 한 자리만 남긴다.** 목적은 다시 들어왔을 때 지도가 그 자리를
-- 기준으로 뜨는 것이고, 그 목적에는 최신 값 하나면 된다. 지나온 자리를 줄줄이 쌓으면
-- 그것은 출소자의 동선 기록이 되는데, 이 결정으로 승인된 범위가 아니다.
--
-- 좌표는 암호화해 넣는다. 이름·생일과 같은 방식이며, 우리가 이 값으로 검색하지 않으므로
-- 암호화가 어떤 편의도 깎지 않는다.

alter table app_user
  add column if not exists place_enc text,
  add column if not exists place_at  timestamptz;

comment on column app_user.place_enc is
  '마지막 위치. {"sido","district","dong","lat","lng"} JSON을 앱에서 암호화한 값이다.';
comment on column app_user.place_at is
  '그 위치를 알아낸 때. 오래된 값으로 엉뚱한 동네를 안내하지 않으려고 함께 둔다.';
