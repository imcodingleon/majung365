-- AI가 제안한 다음 질문 — 기획서 §6.1
--
-- 답변을 다 읽은 사용자가 이어서 무엇을 물어야 할지 다시 막힌다. 대화가 시작되면
-- 첫 질문 칩이 사라지기 때문이다. 그 자리를 답변 흐름에 맞는 질문 셋으로 잇는다.
--
-- **답변과 같은 행에 둔다.** 별도 테이블로 빼면 보관 기간과 파기 경로가 하나 더
-- 늘어나는데(§9.4), 이 값은 그 답변에 딸린 것이라 답변보다 오래 살 이유가 없다.
-- 같은 행에 두면 `clear()`의 행 삭제와 1년 파기가 그대로 덮는다.
--
-- **본문과 같은 방식으로 암호화한다.** 제안 문장 자체는 사용자가 쓴 말이 아니지만,
-- 무엇을 물으려 했는지가 곧 그 사람의 사정을 드러낸다.
--
-- **이 마이그레이션을 코드 배포보다 먼저 적용한다.** 컬럼이 없는 채로 새 코드가
-- 올라가도 저장·조회가 살아남게 저장소에 폴백을 두었지만(message_repository.py),
-- 그 폴백이 도는 동안에는 제안이 남지 않는다.

alter table chat_message
  add column if not exists suggestions_enc text;

