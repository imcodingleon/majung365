-- 방문 알림에 초기 진단 답변을 싣는다 — 기획서 §7.4
--
-- **답변을 상시 저장하지 않는다.** 가입 때 받은 답은 할 일을 계산하고 그대로
-- 버린다. 서버에 계속 두면 "오늘 밤 잘 곳이 없다 · 통장이 압류됐다 · 정신과
-- 상담이 필요하다"가 한 줄에 모이는데, 그것은 출소 사실보다 더 구체적인
-- 취약성 목록이고 유출됐을 때 피해가 이름·생일보다 크다(§9.1 데이터 최소화).
--
-- 대신 **방문 요청을 보내는 그 순간의 답을 그 건에만 붙인다.** 방문 일정이
-- 끝나고 3개월이면 요청과 함께 파기된다(§9.5).

alter table visit_request
  -- 담당자에게 보낼 답변. 사용자가 화면에서 고른 분야만 담긴다.
  -- **자유 입력이 섞이므로 암호화한다** — "하고 싶은 말"과 같은 취급이다.
  add column if not exists shared_answers_enc text,

  -- 언제 동의했는가. §3.4의 제3자 제공 동의는 제공 항목을 "성명, 방문 희망
  -- 일시, 방문 목적"으로 적고 있어 진단 답변은 그 범위 밖이다. 그래서 방문마다
  -- 따로 받고, **나중에 "무엇에 동의했는지"를 확인할 수 있도록 시점을 남긴다.**
  --
  -- 이 값이 없으면 shared_answers_enc도 없다. 서버가 그렇게 강제한다.
  add column if not exists shared_answers_consented_at timestamptz;
