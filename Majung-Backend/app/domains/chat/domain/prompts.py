def build_triage_instruction(route_label: str = "") -> str:
    """분류 지시문. **지금 보고 있는 할 일을 알려준다.**

    저리터러시 사용자는 짧게 묻는다 — "잃어버렸는데 어떡해요?"에는 무엇을
    잃어버렸는지가 없다. 방을 모르면 모델은 그 말만 보고 다른 항목을 고르고,
    그 항목이 곁가지 자료의 출처가 되어 답이 통째로 그쪽으로 샌다(2026-08-31 결함).

    **그래도 다른 항목을 고를 길은 막지 않는다.** R14 카드에서 열었더라도
    "신분증은 어디서 만드나요"를 물을 수 있다. 짐작의 기준점을 줄 뿐이다.
    """
    if not route_label:
        return TRIAGE_INSTRUCTION
    return (
        f"{TRIAGE_INSTRUCTION}\n\n"
        f"참고: 이분은 지금 '{route_label}' 화면에서 묻고 계십니다. "
        "짧게 물어 무엇에 대한 질문인지 문장만으로 알기 어려우면 이 항목으로 보세요. "
        "다만 분명히 다른 것을 물으셨다면 그 항목을 고르세요 — 이것은 짐작의 기준점이지 정답이 아닙니다."
    )


def route_display(route: RouteId) -> str:
    return label_for(route)


def build_guidance_context(
    triage: TriageResult,
    injected_cards: list[str],
    stage: EvidenceStage = EvidenceStage.CONFIRMED,
    passages: list[str] | None = None,
    pinned: RouteId | None = None,
    other_passages: list[str] | None = None,
    user_context: str = "",
    constraint_lines: list[str] | None = None,
) -> str:
    """가이던스 생성 호출에 붙일 컨텍스트(확인된 정보 + triage 요약).

    **탭에서 연 대화는 주제가 이미 정해져 있다.** 예전에는 triage가 고른 항목을
    `[지금 급한 일]` 한 줄에 전부 나열했는데, 그러면 카드를 그 탭 것으로 막아도
    본문이 다른 항목으로 끌려갔다 — 수용·출소증명서 대화에 주거비 안내가 끼어든
    것이 그 경로다. 지금 보고 있는 항목과 곁가지로 나온 항목을 갈라서 적는다.
    """
    lines: list[str] = []
    if pinned is not None:
        lines.append(f"[지금 보고 있는 할 일] {label_for(pinned)}")
        others = [p.route for p in triage.priorities if p.route != pinned]
        if others:
            # **곁가지를 막지는 않는다.** "잘 곳도 없어요"를 꺼낸 사람을 돌려보내지
            # 않되, 그 항목의 자세한 안내는 그쪽 화면이 맡는다(§5.1 서류철 인덱스 탭).
            lines.append(
                f"[함께 꺼내신 이야기] {', '.join(label_for(r) for r in others)} — "
                "짧게만 답하고, 자세한 것은 그 할 일 화면에서 볼 수 있다고 알려 주세요. "
                "이 대화의 주제는 위의 '지금 보고 있는 할 일'입니다"
            )
    elif triage.priorities:
        prio = ", ".join(label_for(p.route) for p in triage.priorities)
        lines.append(f"[지금 급한 일] {prio}")
    if user_context:
        # 진단 판정. **판정만 오고 답변 원문은 오지 않는다**(user_context.py).
        lines.append(user_context)
    if constraint_lines:
        # 수용 사유에 따라 달라지는 사실. **사람이 검수한 문장만 온다**(§9.4).
        #
        # 이 블록을 주지 않고 수용 사유만 알리면 모델이 법률 제약을 **상상해서**
        # 말한다. 그것이 이 기능의 가장 큰 실패 모드다 — 없는 제약을 사실처럼
        # 말하면 사용자가 지레 포기한다.
        lines.append(
            "[수용 사유에 따라 달라지는 것 — 사실관계가 확인된 문장입니다]"
        )
        lines.extend(constraint_lines)
        lines.append(
            "**여기 없는 법률 제약을 지어내지 마세요.** 조문 번호나 처벌 이야기를 "
            "먼저 꺼내지 말고, 무엇을 하면 되는지로 답하세요."
        )
    if passages:
        # 근거 문서 본문. 카드가 제도의 요약이라면 이쪽은 원문이라 구체적인 질문에 답한다.
        lines.append("[수집한 공식 자료 — 이 내용을 근거로 답하고, 어느 기관 자료인지 밝히세요]")
        lines.extend(passages)
    if injected_cards:
        lines.append(
            "[확인된 정보 — 먼저 이 사실을 근거로 쉬운 말로 안내하세요. "
            "여기에 답이 없는 것을 물었다면 web_search로 찾아서 답하세요]"
        )
        lines.extend(injected_cards)
    if other_passages:
        # 그 항목에 근거가 없어 넓혀서 찾은 것. **어디서 온 자료인지 갈라서 준다** —
        # 섞어 놓으면 곁가지 자료가 본 주제의 근거인 것처럼 읽힌다.
        #
        # **주제 자료 뒤에 둔다** (2026-08-31, 실사용 결함으로 고침). 모델은 위에서부터
        # 읽고 먼저 읽은 것으로 답을 시작한다. 예전에는 이 블록이 위에 있었는데,
        # 그 항목에 근거가 없는 방(R13처럼 자료가 적은 항목)에서는 곁가지만 본문이고
        # 주제는 카드 한 줄 요약뿐이라 답이 통째로 그쪽으로 갔다 — R13 방에서 물었는데
        # 신분증(R9) 재발급 안내가 첫 문단으로 나왔다. 모델은 순서를 따랐을 뿐이다.
        lines.append(
            "[다른 할 일에 관한 자료 — **위의 주제에 먼저 답한 뒤**, "
            "물어보신 만큼만 짧게 덧붙이세요. 이것으로 답을 시작하지 마세요]"
        )
        lines.extend(other_passages)
    if not injected_cards and not passages and not other_passages:
        lines.append(
            "[확인된 제도 정보 없음 — **먼저 web_search로 찾아보세요.** "
            "올해 기준액이나 최근 바뀐 제도처럼 우리 자료에 없는 것이 많습니다. "
            "검색해도 못 찾았을 때만 '정확히는 모른다'고 말하고 확인할 곳"
            "(주민센터·129 등)을 알려주세요. 어느 쪽이든 지어내지는 마세요]"
        )
    # **도구가 있다는 것을 모델이 알아야 쓴다.** 판정을 모델에게 넘긴 뒤에도
    # 프롬프트가 "이 사실만"이라고 말하고 있어서 검색이 일어나지 않았다.
    # 회피 답변은 모델이 지시를 충실히 따른 결과였다(2026-08-24).
    lines.append(
        "[web_search 도구를 쓸 수 있습니다 — 공공기관 사이트로 제한되어 있어 안전합니다. "
        "위 자료로 답할 수 없는 질문이면 '모른다'고 끝내지 말고 검색해서 답하세요. "
        "올해 바뀐 금액·기준, 최신 제도 변경이 그렇습니다. "
        # **기관 주소·전화번호는 검색으로 가져오지 않는다.** 사람이 확인한 표가
        # 위 근거에 실려 오고(§6.4 · route-contacts.md), 검색으로 나오는 번호는
        # 지역 지부와 시스템 헬프데스크가 섞인다.
        "**다만 기관 주소·전화번호는 검색하지 마세요** — 위 근거에 있으면 그것을 쓰고, "
        "없으면 대표번호나 주민센터로 안내하세요]"
    )
    if stage == EvidenceStage.WEB:
        # 인터넷에서 온 답임이 말투에 드러나야 한다. 확실성이 다른데 같은 어조로
        # 말하면 사용자가 검색 결과를 제도 안내로 믿는다.
        lines.append(
            f"[인터넷 검색으로 답하는 상황 — 이렇게 시작하세요: \"{WEB_RESULT_OPENING}\" 어느 기관 사이트에서 나온 내용인지 함께 밝히세요]"
        )
    return "\n".join(lines)
