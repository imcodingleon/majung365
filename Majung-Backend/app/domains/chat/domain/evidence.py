"""AI 답변의 근거 단계 — 순수 Python (Domain).

기획서 §6.4. **AI가 어디서 가져온 답인지에 따라 말투와 마무리가 달라진다.**
근거의 확실성이 다른데 같은 어조로 말하면 사용자는 인터넷에서 주워온 말을 제도
안내로 믿는다. 공공 제도 안내에서 오정보는 헛걸음과 불이익으로 직결된다.
"""

from enum import StrEnum


class EvidenceStage(StrEnum):
    """① 확인된 자료에서 찾았는가, ② 인터넷을 뒤졌는가."""

    CONFIRMED = "confirmed"  # 수집한 근거 문서·KB에서 찾았다
    WEB = "web"  # 못 찾아서 인터넷을 찾아본다


# ② 단계의 사전 고지. **검색을 시작하기 전에** 내보낸다.
#
# 나중에 "인터넷 정보였습니다"라고 덧붙이면 이미 사용자는 그것을 사실로 받아들인
# 뒤다. **확실성이 낮다는 신호가 정보보다 앞서야 한다.**
#
# 이 문장은 로딩 안내를 겸한다 — 웹 검색이 붙으면 응답이 느려지는데 사전 고지가
# 그 시간 동안 화면을 채운다. 리스크 고지와 대기 안내가 한 문장으로 해결된다.
WEB_SEARCH_NOTICE = "지금 가지고 있는 자료에서는 관련 내용을 찾지 못했어요. 인터넷에서 찾아볼게요."

# 검색 결과를 여는 말. 모델이 이 톤으로 답하도록 컨텍스트에 넣는다.
WEB_RESULT_OPENING = "인터넷에서 찾아보니 이렇게 나오네요. 다만 확인이 필요할 수 있어요."


def notice_for(stage: EvidenceStage) -> str:
    """그 단계에서 답변보다 먼저 내보낼 문장. 확인된 자료면 없다."""
    return WEB_SEARCH_NOTICE if stage == EvidenceStage.WEB else ""
