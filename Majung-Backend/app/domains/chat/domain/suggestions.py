"""AI가 제안하는 다음 질문 — 순수 Python (Domain), 기획서 §6.1.

답변을 다 읽은 사용자가 이어서 무엇을 물어야 할지 다시 막힌다. 대화가 시작되면
첫 질문 칩이 사라지기 때문이다. 그 자리를 답변 흐름에 맞는 질문 셋으로 잇는다.

프롬프트를 Domain에 두는 이유는 `visit/domain/summary.py`와 같다. **무엇을 묻게
하고 무엇을 막을지가 곧 이 서비스의 판단**이라, 어댑터에 두면 모델을 바꿀 때
함께 흔들린다.

여기서 정하는 선은 셋이다.

1. **질문이 곧 답이 되어서는 안 된다.** "긴급지원은 3일 안에 나와요?"처럼 사실을
   품은 문장을 질문 자리에 넣으면, 사용자는 그것을 확인된 안내로 읽는다. 눌러서
   확인하기 전에 이미 믿는다.
2. **없는 제도를 묻게 하지 않는다.** "○○지원도 받을 수 있나요?"에서 ○○이 우리가
   모르는 제도면, 눌렀을 때 "그런 것은 없어요"가 돌아온다. 지원 항목 목록 안에서만
   고르게 묶는다.
3. **사용자가 하는 말이다.** 이 문장은 눌리는 순간 사용자의 질문이 되므로
   해요체 대화투다(`copy-voice.md` §5). 시스템이 하는 말과 갈래가 다르다.

**모델의 말을 그대로 믿지 않는다.** 위 셋은 프롬프트로 부탁하는 것일 뿐이라,
`normalize_suggestions`가 받은 것을 한 번 더 거른다. 거르는 자리를 어댑터가 아니라
여기 둔 이유는 구현이 셋(Claude·CLI·Mock)이기 때문이다 — 어댑터에 두면 세 벌이 된다.
"""

# 한 번에 내는 개수. **정확히 셋이다.** 화면 폭에도 셋이 맞고, 넘으면 고르는 일
# 자체가 부담이 된다.
WANTED = 3
# 칩 하나가 한 줄을 넘기면 가로 스크롤에서 읽히지 않는다. 첫 질문(15자)보다
# 조금 넉넉히 두는 것은 대화 맥락이 붙은 질문이 그만큼 길어지기 때문이다.
MAX_QUESTION_CHARS = 24

# 모델에게 요구하는 모양.
#
# **`minItems`를 걸지 않는다.** 셋을 못 맞췄다고 스키마 위반으로 통째로 실패하면
# 두 개라도 건질 수 있던 경우까지 잃는다. 개수 판정은 아래 정규화가 맡는다.
SUGGESTIONS_SCHEMA = {
    "type": "object",
    "properties": {
        "questions": {
            "type": "array",
            "maxItems": 5,
            "items": {"type": "string"},
            "description": "사용자가 이어서 물어볼 만한 질문. 물음표로 끝나는 한 문장.",
        },
    },
    "required": ["questions"],
    "additionalProperties": False,
}

SUGGESTIONS_INSTRUCTION = """지금까지의 대화를 읽고, 이분이 이어서 물어볼 만한 질문을 세 개 뽑아 주세요.

이 질문들은 화면에 버튼으로 뜨고, 누르면 그대로 이분의 다음 질문이 됩니다.

이렇게 씁니다.
- 이분이 직접 말하듯 씁니다. "돈이 드나요?", "어디로 가면 돼요?" 같은 해요체입니다.
- 한 문장이고 물음표로 끝납니다.
- 짧게 씁니다. 스무 글자를 넘기지 않습니다.
- 방금 받은 답에서 자연스럽게 이어지는 것을 고릅니다.
- 이미 답해 드린 것은 다시 묻게 하지 않습니다.

이것은 쓰지 않습니다.
- **답이 들어 있는 질문.** "3일 안에 나와요?"처럼 쓰면 이분은 눌러 보기도 전에
  그것을 사실로 믿습니다. 아직 확인해 드리지 않은 것을 질문 안에 넣지 마세요.
- **아래 목록에 없는 제도 이름.** 없는 것을 물으면 "그런 것은 없어요"가 돌아옵니다.
- 전화번호나 기관 주소. 그것은 화면이 따로 안내합니다.
- 판단하거나 캐묻는 말. 과거를 묻지 않습니다.

물어볼 만한 것이 마땅치 않으면 억지로 세 개를 채우지 말고 적게 내도 됩니다."""


def build_suggestions_context(route_labels: list[str]) -> str:
    """제안에 실을 지원 항목 목록.

    **이름을 지어내지 못하게 우리가 아는 것을 먼저 보여준다.** `prompts.py`의
    `_ROUTE_CATALOG`와 같은 방식이며, 여기서는 라벨만 있으면 된다 — 코드(R번호)는
    사용자가 누를 문장에 쓰이지 않는다.
    """
    if not route_labels:
        return ""
    return "우리가 안내할 수 있는 것: " + ", ".join(route_labels)


def normalize_suggestions(raw: list[str] | tuple[str, ...]) -> tuple[str, ...]:
    """모델이 낸 것을 화면에 낼 수 있는 형태로 거른다.

    **셋을 채우지 못하면 빈 튜플을 돌려준다.** 하나나 둘만 내면 칩 줄이 어중간하게
    비고, 사용자는 나머지가 로딩 중인지 없는 것인지 알 수 없다. 유스케이스가 빈
    값을 보고 이벤트 자체를 보내지 않는다 — 빈 배열을 보내면 화면이 "빈 칸"과
    "없음"을 가리지 못한다.
    """
    picked: list[str] = []
    seen: set[str] = set()
    for item in raw:
        question = item.strip()
        # **질문은 질문으로 끝나야 한다.** 서술문이 오면 사실을 담은 문장일
        # 가능성이 높고, 그것이 질문 자리에 있으면 확인된 안내로 읽힌다.
        if not question.endswith("?"):
            continue
        if len(question) > MAX_QUESTION_CHARS or question in seen:
            continue
        seen.add(question)
        picked.append(question)
        if len(picked) == WANTED:
            break
    return tuple(picked) if len(picked) == WANTED else ()
