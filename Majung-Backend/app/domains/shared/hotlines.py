"""공공 상담·안내 번호 — 순수 Python (Domain).

출처: _bmad-output/specs/spec-majung-2nd/route-contacts.md

**번호는 사람이 확인해 여기 적는다.** 근거 문서 본문에서 자동 추출하지 않는다 —
지역 지부 번호와 시스템 헬프데스크 번호가 대표번호처럼 섞여 나오기 때문이다.
그 표가 사람 손으로 정리된 이유가 그것이다.

두 곳이 이 목록을 쓴다.
- KB 제도의 연락처(institutions.json) — 화면에 내보내는 값
- 마스킹 계층 — 사용자가 "129에 전화했는데요"라고 쓴 것을 지우지 않기 위해

목록이 두 벌이면 한쪽만 갱신되는 날이 온다. 그래서 한곳에 둔다.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Hotline:
    """공공 상담 창구 하나.

    **기관명을 번호와 반드시 함께 낸다.** "1670-7004"만 있으면 어디에 거는지 알 수 없다.
    """

    number: str
    org: str
    # 확인된 곳만 채운다. 모르는 시간을 지어내면 닫힌 시간에 걸게 된다.
    hours: str = ""


# 대체 번호. 항목에 연락처가 없으면 공단 대표번호로 보낸다.
KOREHA = "1670-7004"

HOTLINES: dict[str, Hotline] = {
    "110": Hotline("국번없이 110", "정부민원안내콜센터"),
    "119": Hotline("119", "응급"),
    "129": Hotline("129", "보건복지상담센터"),
    "132": Hotline(
        "국번 없이 132",
        "대한법률구조공단",
        # 점심시간에 끊긴다. 그 시간에 건 사용자가 서비스가 없다고 오해한다.
        "평일 09:00~11:50, 13:00~17:50",
    ),
    "1350": Hotline("국번없이 1350", "고용노동부 고객상담센터"),
    "1363": Hotline("1363", "교정민원콜센터"),
    "1577-0199": Hotline("1577-0199", "정신건강 위기상담전화"),
    "1577-1000": Hotline("1577-1000", "국민건강보험공단", "평일 09:00~18:00"),
    "1588-2188": Hotline("1588-2188", "정부24 헬프데스크"),
    "1600-5500": Hotline("1600-5500", "신용회복위원회"),
    KOREHA: Hotline(KOREHA, "한국법무보호복지공단"),
}

# 마스킹이 지우면 안 되는 번호들. 사용자가 대화에 적은 공공 번호는 개인정보가 아니라
# 맥락이다 — 지우면 모델이 무슨 일이 있었는지 모른다.
PUBLIC_HOTLINE_NUMBERS: frozenset[str] = frozenset(HOTLINES)


def hotline(key: str) -> Hotline | None:
    """번호로 찾는다. 없으면 None — 목록에 없는 번호를 화면에 내지 않는다."""
    return HOTLINES.get(key)
